"""
HOW TRIGGERS AND BACKEND INTERACT:

1. TRIGGER INSERTION (MySQL Layer)
   └─ Trigger detects condition
      └─ INSERT Alert record into Alert table
         └─ Backend polling or real-time API reads new alert

2. ALERT TYPES AND THEIR TRIGGERS:
   
   a) material_low (Material Inventory)
      Trigger: AFTER UPDATE ON Material
      Condition: NEW.quantity <= NEW.reorder_threshold
      Alert: {"ref_table": "Material", "ref_id": material_id, "type": "material_low"}
      
   b) cost_overrun (Budget Exceeded)
      Trigger: AFTER INSERT ON Cost
      Condition: SUM(Cost.amount) > Budget.estimated_budget
      Alert: {"ref_table": "Cost", "ref_id": cost_id, "type": "cost_overrun"}
      
   c) task_delay (Overdue Tasks)
      Trigger: AFTER UPDATE ON Task
      Condition: CURDATE() > planned_end AND status != 'completed'
      Alert: {"ref_table": "Task", "ref_id": task_id, "type": "task_delay"}
      
   d) safety_incident (Safety Issues)
      Trigger: AFTER INSERT ON SafetyIncident
      Condition: ALWAYS (automatic alert creation)
      Alert: {"ref_table": "SafetyIncident", "ref_id": incident_id, "type": "safety_alert"}

3. BACKEND RESPONSIBILITIES (API Layer)
   ✓ READ: Fetch active/resolved alerts
   ✓ FILTER: By area, severity, type
   ✓ UPDATE: Mark alert as resolved (is_resolved, resolved_at)
   ✓ DELETE: Remove acknowledged/archived alerts
   ✗ CREATE: NEVER insert alerts (triggers only)

4. FRONTEND USAGE
   GET /alerts -> Display active alerts
   GET /alerts/active -> Critical view
   GET /alerts/by-severity/critical -> Red alerts
   PUT /alerts/{id}/resolve -> User acknowledges
   GET /alerts/stats/summary -> Dashboard metrics

5. DATABASE TRIGGERS (SQL - NOT backend code)
   Example trigger:
   
   CREATE TRIGGER alert_material_low
   AFTER UPDATE ON Material
   FOR EACH ROW
   BEGIN
     IF NEW.quantity <= NEW.reorder_threshold THEN
       INSERT INTO Alert (
         area_id, alert_type, ref_table, ref_id, 
         message, severity
       ) VALUES (
         NEW.area_id, 'material_low', 'Material', NEW.material_id,
         CONCAT('Material ', NEW.name, ' below reorder threshold'),
         'warning'
       );
     END IF;
   END;

6. SCALABILITY NOTE
   For high-volume systems, consider:
   - WebSocket connection for real-time alerts
   - Message queue (RabbitMQ) for async processing
   - Alert aggregation to prevent duplicate entries
"""
